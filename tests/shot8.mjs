import { createRequire } from 'node:module';
import fs from 'node:fs';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const [out, team = '1'] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--enable-webgl'] });
const page = await browser.newPage({ viewport: { width: 1120, height: 630 } });
const logs = [];
page.on('console', (m) => { if (m.type() === 'error') logs.push(m.text()); });
page.on('pageerror', (e) => logs.push('[pageerror] ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 5).join('\n')));
await page.addInitScript((t) => localStorage.setItem('apex-grand-prix.v1', JSON.stringify({ config: { trackId: 'rade', laps: 1, level: 0.3, fieldSize: 5, playerGrid: 2, team: +t, mode: 'race' }, settings: { quality: 'low', camera: 'chase' } })), team);
await page.goto('http://localhost:8099/index.html');
await page.waitForTimeout(4000);
await page.click('[data-act=quick]');
await page.waitForSelector('#hud:not(.hidden)', { timeout: 120000 });
await page.waitForTimeout(600);
const done = await page.evaluate(() => { const a = window.apex; return a.debugUntil(() => a.session.player.rs.finished, 300); });
console.log('player finished:', done);
await page.waitForTimeout(8000);
await page.screenshot({ path: `${out}/finish-scene.png`, timeout: 120000 });
const st = await page.evaluate(() => ({ pos: window.apex.session.player.rs.pos, fin: !!window.apex.session.fin, mode: window.apex.session.camRig.mode, finVisible: !document.getElementById('finish').classList.contains('hidden') }));
console.log(JSON.stringify(st));
await page.waitForFunction(() => window.apex.session.fin && window.apex.session.fin.t > 2, null, { timeout: 120000 });
await page.keyboard.press('Enter');
await page.waitForSelector('table.results', { timeout: 120000 });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/finish-results.png`, timeout: 120000 });
console.log(logs.join('\n') || 'no errors');
await browser.close();
