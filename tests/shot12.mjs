// Night race + photo mode screenshots. Usage: node tests/shot12.mjs outdir [trackId]
import { createRequire } from 'node:module';
import fs from 'node:fs';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const [out, track = 'lumiere'] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--enable-webgl'] });
const page = await browser.newPage({ viewport: { width: 1120, height: 630 } });
const logs = [];
page.on('console', (m) => { if (m.type() === 'error') logs.push(m.text()); });
page.on('pageerror', (e) => logs.push('[pageerror] ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 4).join('\n')));
await page.addInitScript((t) => localStorage.setItem('apex-grand-prix.v1', JSON.stringify({ config: { trackId: t, laps: 5, level: 0.4, fieldSize: 8, playerGrid: 3, team: 1, mode: 'race', weather: 'dry', timeOfDay: 'night' }, settings: { quality: 'high', camera: 'chase' } })), track);
await page.goto('http://localhost:8099/index.html');
await page.waitForTimeout(4000);
await page.click('[data-act=quick]');
await page.waitForSelector('#hud:not(.hidden)', { timeout: 180000 });
await page.waitForTimeout(500);
await page.evaluate(() => { const a = window.apex; a.session.introCancelled = true; a.debugSkip(14); });
await page.waitForTimeout(3000);
await page.screenshot({ path: `${out}/night-chase.png`, timeout: 180000 });
await page.evaluate(() => { window.apex.session.camRig.setMode('heli'); });
await page.waitForTimeout(3000);
await page.screenshot({ path: `${out}/night-heli.png`, timeout: 180000 });
await page.evaluate(() => { window.apex.pause(); window.apex.startPhoto(); });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/photo.png`, timeout: 180000 });
console.log(logs.join('\n') || 'no errors');
await browser.close();
