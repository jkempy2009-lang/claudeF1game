import { createRequire } from 'node:module';
import fs from 'node:fs';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const [out, trackId = 'vettore', skip = '12'] = process.argv.slice(2);
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--enable-webgl'] });
const page = await browser.newPage({ viewport: { width: 1120, height: 630 } });
const logs = [];
page.on('console', (m) => { if (m.type() === 'error') logs.push(m.text()); });
page.on('pageerror', (e) => logs.push('[pageerror] ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 5).join('\n')));
await page.addInitScript((tid) => localStorage.setItem('apex-grand-prix.v1', JSON.stringify({ config: { trackId: tid, laps: 5, level: 0.6, fieldSize: 6, playerGrid: 3, team: 1, mode: 'race' }, settings: { quality: 'low', camera: 'chase' } })), trackId);
await page.goto('http://localhost:8099/index.html');
await page.waitForTimeout(4000);
await page.click('[data-act=quick]');
await page.waitForSelector('#hud:not(.hidden)', { timeout: 120000 });
await page.waitForTimeout(800);
await page.evaluate((s) => { const a = window.apex; a.debugSkip(10); return a.debugUntil(() => a.session.player.s > +s && a.session.player.s < +s + 300, 120); }, skip);
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/line-${trackId}.png`, timeout: 120000 });
console.log(logs.join('\n') || 'no errors');
await browser.close();
