import { ACHIEVEMENTS, recordSession } from '../src/sim/achievements.js';
let bad = 0;
const ok = (n, c, x = '') => { console.log(`${c ? 'PASS' : 'FAIL'}  ${n} ${x}`); if (!c) bad++; };
const save = {};
const base = { kind: 'race', pos: 1, grid: 20, cars: 20, laps: 5, finishedRace: true, penalty: 0, damaged: false, passes: 12, level: 1, wet: true, night: false, km: 25, stops: 1, perfectStops: 1, fastest: true };
const u1 = recordSession(save, base);
ok('first win unlocks several achievements', ['first', 'podium', 'win', 'fl', 'lastfirst', 'tenpass', 'clean', 'perfectstop', 'rain', 'legend', 'grid20'].every((id) => u1.includes(id)), u1.join(','));
ok('stats were counted', save.stats.races === 1 && save.stats.wins === 1 && save.stats.km === 25 && save.stats.passes === 12);
const u2 = recordSession(save, base);
ok('achievements unlock only once', !u2.includes('first') && !u2.includes('win'));
ok('night owl needs a night win', !save.achievements.night);
recordSession(save, { ...base, night: true, wet: false });
ok('night win unlocks night owl', !!save.achievements.night);
recordSession(save, { kind: 'quali', pos: 1, km: 5 });
ok('pole unlocks', !!save.achievements.pole);
recordSession(save, { kind: 'championship', pos: 1 });
ok('championship unlocks', !!save.achievements.champ);
ok('every achievement has a name and description', ACHIEVEMENTS.every((a) => a.name && a.desc && typeof a.test === 'function'));
process.exit(bad ? 1 : 0);
